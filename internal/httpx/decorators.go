package httpx

import "net/http"

// Decorators — обёртки, которые сборщик навешивает на маршруты модуля.
// Auth означает «доступ только аутентифицированному», Anonymous — «доступен всем,
// но не без лимита» (§5.2). Модуль не знает ни про JWT, ни про token bucket:
// он только выбирает, к какому классу относится маршрут.
//
// Node — то же для узлового токена: Subject у запроса не человек, а vpn-сервер,
// поэтому проверка и ключ лимита у него свои (задача 11).
//
// Admin — четвёртый класс (задача 12): админ не «пользователь с другим id», а другой
// класс доступа — другой iss в токене, другой бакет лимитера и право на чужие данные.
// Пакет по-прежнему не импортирует ни auth, ни admin: сборщик передаёт готовую обёртку,
// и модуль только выбирает класс, не зная, как устроен вход.
//
// Контракт с несколькими обёртками, а не с одной, появился из-за лимитов: если бы
// публичные маршруты монтировал сам модуль без обёртки, сборщику пришлось бы
// перемонтировать их второй раз — а ServeMux на повторный шаблон паникует.
type Decorators struct {
	Auth      func(http.Handler) http.Handler
	Anonymous func(http.Handler) http.Handler
	Node      func(http.Handler) http.Handler
	Admin     func(http.Handler) http.Handler
}
